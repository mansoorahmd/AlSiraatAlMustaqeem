-- 0018_revisions_parts_skips — three small changes to the reader's research, private to the
-- account like the rest (row-level security, the one own_rows policy of 0010).
--
--   revisions     an earlier text the reader replaced, kept with its date and (if they say) why:
--                 a word form's established meaning on a case, a case's verdict, their own meaning
--                 for a root, an indication's text. It takes over from form_revisions, which only
--                 knew the first of those and had no reason.
--   mentions      gain `part`: 0 = the word itself; 1, 2 … = that pronoun of the word, as the
--                 corpus numbers them, so the two pronouns of one word (خَلَقْنَـٰكُمْ) are two places.
--                 One mention per character per place still holds, with the part in the place.
--   speech_skips  a speech opener (قال، نادى …) the reader set aside as "no speech here".
--
-- These tables are under FORCE ROW LEVEL SECURITY, which binds their owner too. The two
-- statements below that must see every account's rows lift FORCE for that statement and put it
-- back, so the move works whichever role runs the migration.

CREATE TABLE IF NOT EXISTS research.revisions (
  user_id uuid NOT NULL DEFAULT research.current_user_id() REFERENCES public.users(id) ON DELETE CASCADE,
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- 'form' (target = case id | lemma), 'verdict' (case id), 'root-meaning' (root), 'indication' (its id)
  kind TEXT COLLATE "C" NOT NULL, target TEXT COLLATE "C" NOT NULL,
  before TEXT COLLATE "C" NOT NULL,
  reason TEXT COLLATE "C" NOT NULL DEFAULT '',
  replaced_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_revisions_target ON research.revisions(user_id, kind, target);

ALTER TABLE research.form_revisions NO FORCE ROW LEVEL SECURITY;
INSERT INTO research.revisions (user_id, kind, target, before, replaced_at)
  SELECT user_id, 'form', case_id || '|' || lemma, meaning, replaced_at
  FROM research.form_revisions ORDER BY id;
DROP TABLE research.form_revisions;

ALTER TABLE research.mentions ADD COLUMN IF NOT EXISTS part BIGINT NOT NULL DEFAULT 0;
ALTER TABLE research.mentions NO FORCE ROW LEVEL SECURITY;
UPDATE research.mentions SET id = id || '|0';
ALTER TABLE research.mentions FORCE ROW LEVEL SECURITY;
ALTER TABLE research.mentions DROP CONSTRAINT IF EXISTS mentions_user_id_character_id_verse_key_word_key;
ALTER TABLE research.mentions ADD CONSTRAINT mentions_place_key UNIQUE (user_id, character_id, verse_key, word, part);

CREATE TABLE IF NOT EXISTS research.speech_skips (
  user_id uuid NOT NULL DEFAULT research.current_user_id() REFERENCES public.users(id) ON DELETE CASCADE,
  verse_key TEXT COLLATE "C" NOT NULL, word BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, verse_key, word)
);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['revisions','speech_skips'] LOOP
    EXECUTE format('ALTER TABLE research.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE research.%I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS own_rows ON research.%I', t);
    EXECUTE format(
      'CREATE POLICY own_rows ON research.%I USING (user_id = research.current_user_id()) WITH CHECK (user_id = research.current_user_id())', t);
  END LOOP;
END $$;

GRANT SELECT, INSERT, UPDATE, DELETE ON research.revisions, research.speech_skips TO mqrg_research;
